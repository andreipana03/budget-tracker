export function isIconName(name: string | null | undefined): name is IconName {
  return !!name && Object.prototype.hasOwnProperty.call(ICONS, name)
}

/**
 * Where an icon sits. The weight rules of design § 4.6 live here, in one place:
 *   tab      fill, 26px  — tab bar
 *   tile     fill        — inside category tiles
 *   sidebar  regular, 18px
 *   toolbar  regular, 17px — desktop toolbar groups
 *   topbar   regular, 21px — compact top-bar glass buttons
 *   inline   regular, or bold for small glyphs next to semibold text (see BOLD_GLYPHS)
 */
export type IconVariant = 'tab' | 'tile' | 'sidebar' | 'toolbar' | 'topbar' | 'inline'

/** Small structural glyphs that are always bold outside tabs and tiles (§ 4.6). */
const BOLD_GLYPHS = new Set<IconName>([
  'caret-left',
  'caret-right',
  'caret-down',
  'caret-up-down',
  'plus',
  'minus',
  'x',
  'check',
  'magnifying-glass',
  'trend-up',
])

const VARIANT_WEIGHT: Partial<Record<IconVariant, IconWeight>> = { tab: 'fill', tile: 'fill' }
export const VARIANT_SIZE: Partial<Record<IconVariant, number>> = { tab: 26, sidebar: 18, toolbar: 17, topbar: 21 }

export function iconWeight(name: IconName, variant: IconVariant = 'inline'): IconWeight {
  return VARIANT_WEIGHT[variant] ?? (BOLD_GLYPHS.has(name) ? 'bold' : 'regular')
}

